"""Create one experiment per ablation from the baseline config: config, docs, sync plan, registry rows.

Never overwrites: an experiment folder that already exists is left alone (configs are immutable).
"""

from __future__ import annotations

import copy
import csv
from pathlib import Path

import yaml

from .plan import Ablation, AblationPlan, check_one_factor, set_key

SUBFOLDERS = ("logs", "metrics", "predictions", "learning_curves", "notebook")


def build_config(base: dict, plan: AblationPlan, ablation: Ablation, git_commit: str, timestamp: str) -> dict:
    config = copy.deepcopy(base)
    exp = ablation.experiment_id
    config["experiment_id"] = exp
    config["model"]["model_id"] = ablation.model_id
    config["study_track"] = "ablation"
    config["purpose"] = (f"Phase E10 ablation of {plan.baseline} ({plan.raw['step']}, DEC0008). Factor: {ablation.factor}. "
                         f"Question: {ablation.question} Everything else is {plan.baseline}'s configuration, "
                         f"including its learning rate.")
    config["expected_outcome"] = ablation.expected_outcome
    config["learning_rate"]["source"] = "manual"
    config["outputs"] = {
        "experiment_dir": f"06_Experiments/{exp}",
        "checkpoint_dir": f"06_Experiments/{exp}/notebook/checkpoints",
        "checkpoint_manifest": f"07_Checkpoints/{exp}_checkpoints.md",
        "artifact_dataset_slug": plan.artifact_slug(exp),
    }
    config["git_commit"] = git_commit
    config["timestamp"] = timestamp
    config["notes"] = (f"Generated by `python -m ablation create` from {plan.baseline}/config.yaml. "
                       f"Changed for the factor: {', '.join(f'{k} = {v}' for k, v in ablation.changes.items())}.")
    for key, value in ablation.changes.items():
        set_key(config, key, value)
    check_one_factor(base, config, ablation)
    return config


def _header(plan: AblationPlan, ablation: Ablation) -> str:
    return (f"# {ablation.experiment_id} — ablation of {plan.baseline}: {ablation.factor} ({plan.raw['step']}, DEC0008).\n"
            "# Generated by `python -m ablation create` from 06_Experiments/ablations/STEP048_plan.yaml.\n"
            f"# Differs from {plan.baseline} only in identity fields and: {', '.join(ablation.changes)}.\n"
            "# Immutable once training starts: any change → new EXP ID.\n\n")


def _readme(plan: AblationPlan, a: Ablation) -> str:
    changes = "\n".join(f"| `{k}` | `{v}` |" for k, v in a.changes.items())
    return f"""# Experiment: {a.experiment_id}

**Status:** ready. Waiting for the STEP-048 Kaggle session (`06_Experiments/ablations/KAGGLE_RUNBOOK.md`).

**Type:** Phase E10 ablation of `{plan.baseline}` (DEC0008). Factor: **{a.factor}**.

**Question:** {a.question}

**Change from {plan.baseline}** (nothing else differs except identity fields):

| Key | Value |
|-----|-------|
{changes}

**Dataset / split:** `DS0001` v1.0 / `PP0001` / `SPLIT0001`, as {plan.baseline}.

**Model:** `{a.model_id}` — ResNet-50, a separately trained instance.

**Expected outcome:** {a.expected_outcome}

**Results:** pending. Comparison: `08_Evaluation/ablations/ablation_report.md`.

**Artifacts:** Kaggle dataset `{plan.artifact_slug(a.experiment_id)}`.
"""


def _observations(plan: AblationPlan, a: Ablation, date: str) -> str:
    return f"""# {a.experiment_id} — Observations

## {date} — Readiness (STEP-048)

- Generated from `{plan.baseline}/config.yaml` by `python -m ablation create`; the one-factor check passed (only identity fields and {', '.join(f'`{k}`' for k in a.changes)} differ).
- `learning_rate.source: manual`: {plan.baseline}'s LR Finder value is reused unchanged so that {a.factor} is the only training difference.
"""


def _checkpoints_info(plan: AblationPlan, a: Ablation) -> str:
    exp, slug = a.experiment_id, plan.artifact_slug(a.experiment_id)
    return f"""# {exp} — Checkpoint Info

**Status:** not trained yet.

| Item | Location |
|------|----------|
| Local checkpoint directory (Kaggle session) | `06_Experiments/{exp}/notebook/checkpoints` |
| Git-side manifest + checksums | `07_Checkpoints/{exp}_checkpoints.md` (written by the training pipeline) |
| Artifact tier (binaries) | Kaggle dataset `{slug}` (created by the first publish) |

Expected files: `{exp}_epoch_NNN.pth`, `{exp}_best.pth`, `{exp}_last.pth`, `{a.model_id}_export.pkl`, `{a.model_id}_weights.pth`.
"""


def sync_plan(plan: AblationPlan, a: Ablation) -> dict:
    exp, slug = a.experiment_id, plan.artifact_slug(a.experiment_id)
    return {
        "repo_url": "https://github.com/isthisdeception/thesis.git", "repo_branch": "main", "repo_dir": "thesis",
        "workspace_root": "/kaggle/working", "kaggle_requirements": "environment/kaggle-requirements.txt",
        "metadata_paths": [f"07_Checkpoints/{exp}_checkpoints.md", f"06_Experiments/{exp}/logs", f"06_Experiments/{exp}/metrics",
                           f"06_Experiments/{exp}/learning_curves", f"06_Experiments/{exp}/predictions",
                           f"06_Experiments/{exp}/notebook/checkpoints/checkpoint_manifest.json"],
        "dataset_mounts": [{"name": "ds0001_processed", "slug": "isthisdeception/ds0001-pp0001",
                            "mount_path": "/kaggle/input/datasets/isthisdeception/ds0001-pp0001", "tier": "data", "required": True}],
        "publish_targets": [{"dataset_slug": slug, "title": f"Thesis {exp} Artifacts", "upload_dir": f"06_Experiments/{exp}",
                             "version_notes": f"{exp} checkpoints and {a.model_id} export from Kaggle", "is_private": True,
                             "convert_to_csv": False}],
    }


def combined_sync_plan(plan: AblationPlan) -> dict:
    """The push plan for the whole session: metadata of every ablation."""

    first = sync_plan(plan, plan.ablations[0])
    paths = [p for a in plan.ablations for p in sync_plan(plan, a)["metadata_paths"]]
    return {**{k: v for k, v in first.items() if k not in {"metadata_paths", "publish_targets"}}, "metadata_paths": paths}


def _append(path: Path, row: list[str]) -> None:
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    with path.open("a", encoding="utf-8", newline="") as f:
        if text and not text.endswith("\n"):
            f.write("\n")
        csv.writer(f, lineterminator="\n").writerow(row)


def _has_row(path: Path, column: str, value: str) -> bool:
    with path.open(encoding="utf-8", newline="") as f:
        return any((r.get(column) or "").strip() == value for r in csv.DictReader(f, skipinitialspace=True))


def register(repo: Path, plan: AblationPlan, a: Ablation, date: str) -> list[str]:
    """Add the experiment, model, dataset-link, and evaluation rows that do not exist yet."""

    added = []
    split = "DS0001_PP0001_SPLIT0001"
    exp_reg = repo / "06_Experiments/experiment_registry.csv"
    if not _has_row(exp_reg, "Experiment ID", a.experiment_id):
        _append(exp_reg, [a.experiment_id, f"Ablation of {plan.baseline} (E10): {a.factor}", plan.raw.get("research_question", ""),
                          f"06_Experiments/{a.experiment_id}/config.yaml", f"DS0001/v1.0/PP0001/{split}", f"{a.model_id} (ResNet-50)",
                          "", "", "", "ready", "none", f"{a.question} One-factor check PASS (DEC0008).",
                          "STEP-048 Kaggle session; then python -m ablation evaluate.", "Experiment Agent", "1.0", date, date])
        added.append("experiment")
    model_reg = repo / "05_Models/model_registry.csv"
    if not _has_row(model_reg, "Model ID", a.model_id):
        _append(model_reg, [a.model_id, a.experiment_id, "DS0001/v1.0/PP0001", split, "ResNet-50", "", "", "", "", "", "", "no",
                            f"Ablation instance of the ResNet-50 baseline ({a.factor}). Registered before training.",
                            "no", "Registry Agent", "1.0", "planned", date, date])
        added.append("model")
    ds_reg = repo / "03_Datasets/metadata/dataset_registry.csv"
    if not _has_row(ds_reg, "Experiment ID", a.experiment_id):
        _append(ds_reg, ["DS0001", "v1.0", "PP0001", split, a.experiment_id, a.model_id, "Registry Agent", "ready", date, date])
        added.append("dataset link")
    eval_reg = repo / "08_Evaluation/evaluation_registry.csv"
    if not _has_row(eval_reg, "Evaluation ID", a.evaluation_id):
        _append(eval_reg, [a.evaluation_id, a.experiment_id, f"DS0001/v1.0/PP0001/{split}", a.model_id, "", "", "", "", "reserved", "1.0",
                           f"Reserved {date} for the E1-E2 check of ablation {a.experiment_id} ({a.factor}).", "Evaluation Agent", date, date])
        added.append("evaluation")
    return added


def create(repo: Path, plan: AblationPlan, git_commit: str, timestamp: str) -> dict[str, list[str]]:
    base = yaml.safe_load((repo / "06_Experiments" / plan.baseline / "config.yaml").read_text(encoding="utf-8"))
    plan.raw.setdefault("research_question", " ".join(str(base["research_question"]).split()))
    date = timestamp[:10]
    report: dict[str, list[str]] = {}
    for a in plan.ablations:
        exp_dir = repo / "06_Experiments" / a.experiment_id
        written = []
        if not (exp_dir / "config.yaml").exists():
            config = build_config(base, plan, a, git_commit, timestamp)
            for sub in SUBFOLDERS:
                (exp_dir / sub).mkdir(parents=True, exist_ok=True)
                (exp_dir / sub / ".gitkeep").touch()
            (exp_dir / "config.yaml").write_text(_header(plan, a) + yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=100),
                                                 encoding="utf-8", newline="\n")
            (exp_dir / "README.md").write_text(_readme(plan, a), encoding="utf-8", newline="\n")
            (exp_dir / "observations.md").write_text(_observations(plan, a, date), encoding="utf-8", newline="\n")
            (exp_dir / "checkpoints_info.md").write_text(_checkpoints_info(plan, a), encoding="utf-8", newline="\n")
            written.append("experiment folder")
        sync = repo / "17_Automation/kaggle_sync" / f"sync_plan.{a.experiment_id.lower()}.yaml"
        if not sync.exists():
            sync.write_text(f"# {a.experiment_id} (STEP-048 ablation, {a.factor}). Generated by `python -m ablation create`.\n"
                            + yaml.safe_dump(sync_plan(plan, a), sort_keys=False), encoding="utf-8", newline="\n")
            written.append("sync plan")
        written += register(repo, plan, a, date)
        report[a.experiment_id] = written
    combined = repo / "17_Automation/kaggle_sync/sync_plan.ablations.yaml"
    combined.write_text("# STEP-048 ablation session: pushes the metadata of every ablation. Generated by `python -m ablation create`.\n"
                        + yaml.safe_dump(combined_sync_plan(plan), sort_keys=False), encoding="utf-8", newline="\n")
    return report
